KEEP_REGULAR = set('«»"\'’→*')


def _grid(rows):
    """Lletra (llista de cadenes des de la fila TOP) -> conjunt de píxels (x, y) i amplada."""
    w = max(len(r) for r in rows)
    return {(x, TOP + y) for y, r in enumerate(rows) for x, c in enumerate(r) if c == '#'}, w


def _embolden(px, w):
    return px | {(x + 1, y) for x, y in px}, w + 1


def _base(ch, bold):
    if bold and ch in BOLD:
        return _grid(BOLD[ch])
    g = _grid(GLYPHS[ch])
    return _embolden(*g) if bold and ch not in KEEP_REGULAR else g


def _compose(base, accent, bold):
    px, w = _base(base, bold)
    mark = (BOLD_ACCENTS if bold else ACCENTS)[accent]
    mw = len(mark[0])
    nw = max(w, mw)
    shift = (nw - w) // 2
    if base == 'ı' and accent == 'grave' and not bold:
        shift = 1                       # el traç de l'accent greu acaba a la dreta: hi posem la i a sota
    px = {(x + shift, y) for x, y in px}
    top = min(y for _, y in px)
    mx = (nw - mw) // 2
    my = top - 1 - len(mark)            # una fila de separació
    px |= {(mx + x, my + y) for y, r in enumerate(mark) for x, c in enumerate(r) if c == '#'}
    return px, nw


def _cedilla(base, bold):
    px, w = _grid(GLYPHS[base])
    cx = w // 2
    px = px | {(cx, BASE), (cx, BASE + 1), (cx - 1, BASE + 2)}
    return _embolden(px, w) if bold else (px, w)


def font640(bold=False):
    """{caràcter: (píxels, amplada)} de la font regular o negreta."""
    out = {ch: _base(ch, bold) for ch in GLYPHS if ch != 'ı'}
    out.update({ch: _compose(b, a, bold) for ch, (b, a) in COMPOSED.items()})
    out.update({ch: _cedilla(b, bold) for ch, b in CEDILLA.items()})
    return out


def text_width(glyphs, s, space=SPACE):
    return sum((space if c == ' ' else glyphs[c][1] + 1) for c in s) - 1


def draw_text(img, glyphs, s, x, y, color, outline=OUTLINE, space=SPACE):
    """Text de mapa de bits a (x, y) (dalt de la graella), amb la vora fosca de baix a la dreta com al joc."""
    P = img.load()
    def rgba(c):                        # tupla RGB o nom/hex de color de PIL
        return Image.new('RGB', (1, 1), c).getpixel((0, 0)) + (255,)
    col = rgba(color)
    ocol = rgba(outline) if outline else None
    pts = []
    cx = x
    for c in s:
        if c == ' ':
            cx += space
            continue
        px, w = glyphs[c]
        pts += [(cx + gx, y + gy) for gx, gy in px]
        cx += w + 1
    if ocol:
        for px_, py_ in pts:
            for dx, dy in ((1, 0), (0, 1), (1, 1)):
                if 0 <= px_ + dx < img.width and 0 <= py_ + dy < img.height:
                    P[px_ + dx, py_ + dy] = ocol
    for px_, py_ in pts:
        if 0 <= px_ < img.width and 0 <= py_ < img.height:
            P[px_, py_] = col


# ─── Exportació (BMFont XML + PNG, com tools/font/conjuraavet_font.py) ─────────────

def build(name, face, glyphs, out_dir):
    chars = sorted(glyphs)
    cols = 16
    cell_w = max(w for _, w in glyphs.values()) + 1
    rows = (len(chars) + 1 + cols - 1) // cols
    sheet = Image.new('RGBA', (cols * cell_w, rows * LINE_H), (0, 0, 0, 0))
    entries = []
    for i, ch in enumerate([' '] + chars):
        x0, y0 = (i % cols) * cell_w, (i // cols) * LINE_H
        if ch == ' ':
            w, adv = SPACE, SPACE
        else:
            px, w = glyphs[ch]
            adv = w + 1
            for x, y in px:
                sheet.putpixel((x0 + x, y0 + y), (255, 255, 255, 255))
        entries.append(f'    <char id="{ord(ch)}" x="{x0}" y="{y0}" width="{w}" height="{LINE_H}" '
                       f'xoffset="0" yoffset="0" xadvance="{adv}" page="0" chnl="15" />')
    sheet.save(out_dir / f'{name}_0.png')
    xml = '\n'.join([
        '<?xml version="1.0"?>',
        '<font>',
        f'  <info face="{face}" size="-{NOMINAL_SIZE}" bold="0" italic="0" charset="" unicode="1" '
        'stretchH="100" smooth="0" aa="1" padding="0,0,0,0" spacing="1,0" outline="0"/>',
        f'  <common lineHeight="{LINE_H}" base="{BASE}" scaleW="{sheet.width}" scaleH="{sheet.height}" '
        'pages="1" packed="0" alphaChnl="0" redChnl="4" greenChnl="4" blueChnl="4"/>',
        '  <pages>',
        f'    <page id="0" file="{name}_0.png" />',
        '  </pages>',
        f'  <chars count="{len(entries)}">',
        *entries,
        '  </chars>',
        '</font>',
        '',
    ])
    (out_dir / f'{name}.xml').write_text(xml, encoding='utf-8')


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    out.mkdir(parents=True, exist_ok=True)
    reg = font640()
    build('conjuraavet-regular', 'Avet Regular', reg, out)
    build('conjuraavet-negreta', 'Avet Negreta', font640(bold=True), out)
    print(f'{len(reg) + 1} caràcters -> {out}')


if __name__ == '__main__':
    main()
